-- ===== Time-bound announcements shown to every signed-in user (releases, deployments, maintenance) =====
create table announcement (
    id          bigint generated by default as identity primary key,
    kind        varchar(20)  not null,          -- INFO | RELEASE | MAINTENANCE | INCIDENT
    message     varchar(500) not null,
    link_url    varchar(500),
    link_label  varchar(60),
    starts_at   timestamp with time zone not null,
    ends_at     timestamp with time zone not null,
    created_by  varchar(200) not null,
    created_at  timestamp with time zone not null default now(),
    updated_by  varchar(200),
    updated_at  timestamp with time zone,
    constraint ck_announcement_window check (ends_at > starts_at)
);
create index ix_announcement_window on announcement (ends_at, starts_at);
