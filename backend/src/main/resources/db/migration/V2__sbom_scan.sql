-- SBOM generation + vulnerability scan results (persisted so history survives restarts).
create table sbom_scan (
    id               bigint generated by default as identity primary key,
    project_name     varchar(200) not null,
    project_version  varchar(100) not null,
    format           varchar(30)  not null,
    generator        varchar(100) not null,
    status           varchar(20)  not null check (status in ('COMPLETED', 'FAILED')),
    component_count  integer not null default 0,
    critical         integer not null default 0,
    high             integer not null default 0,
    medium           integer not null default 0,
    low              integer not null default 0,
    scanned_at       timestamp with time zone not null default now()
);

create table sbom_vulnerability (
    id             bigint generated by default as identity primary key,
    scan_id        bigint not null references sbom_scan (id) on delete cascade,
    vuln_id        varchar(60)  not null,
    severity       varchar(10)  not null check (severity in ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
    component      varchar(300) not null,
    version        varchar(100),
    fixed_version  varchar(100),
    title          varchar(500)
);

create index ix_sbom_scan_project on sbom_scan (project_name, scanned_at desc);
create index ix_sbom_vulnerability_scan on sbom_vulnerability (scan_id);
