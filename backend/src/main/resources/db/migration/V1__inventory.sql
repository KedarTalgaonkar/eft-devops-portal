-- Application inventory: one row per application/client, one deployment per environment and Tomcat context.
create table application (
    id          bigint generated by default as identity primary key,
    name        varchar(200) not null,
    client      varchar(200) not null default '',
    owner       varchar(100),
    created_at  timestamp with time zone not null default now(),
    updated_at  timestamp with time zone not null default now(),
    constraint uq_application unique (name, client)
);

create table deployment (
    id                 bigint generated by default as identity primary key,
    application_id     bigint not null references application (id) on delete cascade,
    environment        varchar(16) not null check (environment in ('DEVELOP', 'SIT', 'UAT')),
    context_name       varchar(200) not null default '',
    base_url           varchar(500),
    tomcat_version     varchar(50),
    java_version       varchar(50),
    tomcat_admin_done  boolean not null default false,
    build_xml_done     boolean not null default false,
    jenkins_job        varchar(300),
    updated_at         timestamp with time zone not null default now(),
    constraint uq_deployment unique (application_id, environment, context_name)
);

create index ix_deployment_environment on deployment (environment);
