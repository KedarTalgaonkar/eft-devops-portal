-- Group-based access to portal modules. A user's access to a module is the best level any of their groups grants,
-- capped by their role (VIEWER = at most VIEW). Administrators always have full access.
create table access_group (
    id           bigint generated by default as identity primary key,
    name         varchar(100) not null,
    description  varchar(300),
    builtin      boolean      not null default false,
    created_at   timestamp with time zone not null default now(),
    updated_at   timestamp with time zone not null default now(),
    updated_by   varchar(200),
    constraint uq_access_group_name unique (name)
);

-- Hidden / view / edit per module; a missing row means NONE (hidden).
create table access_group_module (
    group_id  bigint      not null references access_group (id) on delete cascade,
    module    varchar(30) not null,
    level     varchar(10) not null check (level in ('NONE', 'VIEW', 'EDIT')),
    primary key (group_id, module)
);

-- Members through single sign-on: names or object ids from the ID token's "groups" claim (Entra ID / Keycloak).
create table access_group_sso (
    group_id   bigint       not null references access_group (id) on delete cascade,
    sso_group  varchar(200) not null,
    primary key (group_id, sso_group)
);

-- Members by portal username (local accounts, or individual SSO users).
create table access_group_member (
    group_id  bigint       not null references access_group (id) on delete cascade,
    username  varchar(200) not null,
    primary key (group_id, username)
);

-- "Everyone" applies to every signed-in user. It starts with full access so nothing changes on upgrade;
-- administrators narrow it on Administration > Access groups.
insert into access_group (name, description, builtin, updated_by)
values ('Everyone', 'Applies to every signed-in user. Narrow this, then grant more through other groups.', true, 'system');

insert into access_group_module (group_id, module, level)
select g.id, m.module, 'EDIT'
from access_group g
cross join (values ('DASHBOARD'), ('PIPELINES'), ('SOURCE_CODE'), ('ARTIFACTS'), ('QUALITY'), ('SBOM'), ('MONITORING'), ('INVENTORY')) as m (module)
where g.name = 'Everyone';
