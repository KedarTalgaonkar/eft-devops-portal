-- ===== Server-side HTTP sessions (Spring Session JDBC, PostgreSQL schema) =====
create table spring_session (
    primary_id            char(36)     not null,
    session_id            char(36)     not null,
    creation_time         bigint       not null,
    last_access_time      bigint       not null,
    max_inactive_interval int          not null,
    expiry_time           bigint       not null,
    principal_name        varchar(100),
    constraint spring_session_pk primary key (primary_id)
);
create unique index spring_session_ix1 on spring_session (session_id);
create index spring_session_ix2 on spring_session (expiry_time);
create index spring_session_ix3 on spring_session (principal_name);

create table spring_session_attributes (
    session_primary_id char(36)     not null,
    attribute_name     varchar(200) not null,
    attribute_bytes    bytea        not null,
    constraint spring_session_attributes_pk primary key (session_primary_id, attribute_name),
    constraint spring_session_attributes_fk foreign key (session_primary_id) references spring_session (primary_id) on delete cascade
);

-- ===== Local (database) accounts: break-glass and users without SSO =====
create table portal_user (
    id                    bigint generated by default as identity primary key,
    username              varchar(100) not null,
    display_name          varchar(200) not null,
    email                 varchar(200),
    password_hash         varchar(200) not null,
    roles                 varchar(200) not null default 'VIEWER',
    enabled               boolean      not null default true,
    must_change_password  boolean      not null default true,
    failed_attempts       integer      not null default 0,
    locked_until          timestamp with time zone,
    last_login_at         timestamp with time zone,
    password_changed_at   timestamp with time zone,
    created_at            timestamp with time zone not null default now(),
    created_by            varchar(200)
);
create unique index ux_portal_user_username on portal_user (lower(username));

-- ===== Security audit trail: sign-ins, sign-outs, denials, changes =====
create table audit_event (
    id          bigint generated by default as identity primary key,
    occurred_at timestamp with time zone not null default now(),
    username    varchar(200),
    auth_source varchar(20),
    action      varchar(60)  not null,
    target      varchar(500),
    outcome     varchar(20)  not null,
    ip_address  varchar(64),
    user_agent  varchar(300),
    detail      varchar(1000)
);
create index ix_audit_event_time on audit_event (occurred_at desc);
create index ix_audit_event_user on audit_event (username, occurred_at desc);

