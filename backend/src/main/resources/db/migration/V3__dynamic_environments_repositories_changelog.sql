-- Environments become data: new ones are created on import (e.g. PERF, PREPROD, PROD, DR) instead of being hard-coded.
create table environment (
    code        varchar(32)  primary key,
    name        varchar(100) not null,
    sort_order  integer      not null default 100,
    category    varchar(20)  not null default 'NON_PROD' check (category in ('NON_PROD', 'PROD')),
    active      boolean      not null default true,
    created_at  timestamp with time zone not null default now()
);

insert into environment (code, name, sort_order, category) values
    ('DEVELOP', 'Develop', 10, 'NON_PROD'),
    ('SIT',     'SIT',     20, 'NON_PROD'),
    ('UAT',     'UAT',     30, 'NON_PROD');

alter table deployment drop constraint if exists deployment_environment_check;
alter table deployment
    add constraint fk_deployment_environment foreign key (environment) references environment (code) on update cascade;

-- Platform of the deployment path (Tomcat today; Kubernetes/OpenShift, VM etc. later)
alter table deployment add column platform varchar(30) not null default 'TOMCAT';

-- Source repositories per application (GitHub "org/name"), from the Excel "Repository" column or edited in the portal
create table application_repository (
    application_id  bigint       not null references application (id) on delete cascade,
    repository      varchar(200) not null,
    primary key (application_id, repository)
);

-- Who/what changed in the inventory: owner moves, URL or version changes, new deployment paths, portal edits
create table inventory_change (
    id              bigint generated by default as identity primary key,
    application_id  bigint references application (id) on delete cascade,
    deployment_id   bigint references deployment (id) on delete set null,
    change_type     varchar(30)  not null,
    field           varchar(50),
    old_value       varchar(500),
    new_value       varchar(500),
    source          varchar(20)  not null,
    changed_at      timestamp with time zone not null default now()
);

create index ix_inventory_change_time on inventory_change (changed_at desc);
create index ix_inventory_change_app on inventory_change (application_id, changed_at desc);
