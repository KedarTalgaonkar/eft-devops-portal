-- ===== AI features: usage/cost ledger, stored results, user feedback =====

-- One row per AI call (live or mock): who, which feature, tokens, estimated cost, outcome
create table ai_usage (
    id                 bigint generated by default as identity primary key,
    occurred_at        timestamp with time zone not null default now(),
    feature            varchar(50)  not null,
    subject            varchar(300),
    username           varchar(200) not null,
    mode               varchar(10)  not null,
    model              varchar(100),
    input_tokens       bigint       not null default 0,
    output_tokens      bigint       not null default 0,
    cache_read_tokens  bigint       not null default 0,
    cost_usd           numeric(12, 6) not null default 0,
    duration_ms        bigint       not null default 0,
    outcome            varchar(20)  not null,
    detail             varchar(500)
);
create index ix_ai_usage_time on ai_usage (occurred_at desc);
create index ix_ai_usage_user on ai_usage (username, occurred_at desc);

-- Stored AI results, generated once and reused (a build explanation, a digest)
create table ai_insight (
    id           bigint generated by default as identity primary key,
    feature      varchar(50)  not null,
    subject      varchar(300) not null,
    content      text         not null,
    mode         varchar(10)  not null,
    model        varchar(100),
    masking      varchar(300),
    created_at   timestamp with time zone not null default now(),
    created_by   varchar(200) not null,
    constraint uq_ai_insight unique (feature, subject)
);
create index ix_ai_insight_feature on ai_insight (feature, created_at desc);

-- Thumbs up / down per user and result
create table ai_feedback (
    insight_id  bigint       not null references ai_insight (id) on delete cascade,
    username    varchar(200) not null,
    vote        smallint     not null check (vote in (-1, 1)),
    created_at  timestamp with time zone not null default now(),
    primary key (insight_id, username)
);
