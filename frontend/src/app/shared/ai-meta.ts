import { Component, inject, input, output, signal } from '@angular/core';
import { DatePipe } from '@angular/common';
import { HttpClient } from '@angular/common/http';
import { MatIconModule } from '@angular/material/icon';
import { MatTooltipModule } from '@angular/material/tooltip';
import { apiUrl } from '../core/api';
import { modelLabel, StoredInsight } from '../core/ai';

/**
 * Provenance line under every AI answer ("AI-generated · model · when · what was masked") with helpful /
 * not-helpful buttons. Votes are stored per user; clicking the same vote again withdraws it.
 */
@Component({
  selector: 'app-ai-meta',
  imports: [DatePipe, MatIconModule, MatTooltipModule],
  template: `
    @let r = result();
    <div class="meta">
      <span class="ai-tag" [matTooltip]="'Generated by AI. Check before acting on it.'"
        ><mat-icon aria-hidden="true">auto_awesome</mat-icon>AI-generated</span
      >
      <span>{{ label(r) }}</span>
      <span>·</span>
      <span
        >{{ r.createdAt | date: 'dd MMM, HH:mm'
        }}{{ r.createdBy && r.createdBy !== 'system' ? ' for ' + r.createdBy : '' }}</span
      >
      @if (r.masking) {
        <span
          class="masking"
          [matTooltip]="'Sensitive values were replaced before the data was sent: ' + r.masking"
        >
          <mat-icon aria-hidden="true">shield</mat-icon>{{ r.masking }}
        </span>
      }
      <span class="votes" role="group" aria-label="Was this helpful?">
        <span>Helpful?</span>
        <button
          type="button"
          class="vote"
          [class.on]="r.myVote === 1"
          [disabled]="busy()"
          (click)="vote(1)"
          [attr.aria-pressed]="r.myVote === 1"
          aria-label="Helpful"
          matTooltip="Helpful"
        >
          <mat-icon aria-hidden="true">thumb_up</mat-icon><span>{{ r.helpful }}</span>
        </button>
        <button
          type="button"
          class="vote"
          [class.on]="r.myVote === -1"
          [disabled]="busy()"
          (click)="vote(-1)"
          [attr.aria-pressed]="r.myVote === -1"
          aria-label="Not helpful"
          matTooltip="Not helpful"
        >
          <mat-icon aria-hidden="true">thumb_down</mat-icon><span>{{ r.notHelpful }}</span>
        </button>
      </span>
    </div>
  `,
  styles: `
    .meta {
      display: flex;
      flex-wrap: wrap;
      align-items: center;
      gap: 6px 8px;
      font-size: 12px;
      color: var(--app-muted);
    }
    .ai-tag {
      display: inline-flex;
      align-items: center;
      gap: 4px;
      padding: 2px 8px;
      border-radius: 999px;
      font-weight: 600;
      background: linear-gradient(90deg, #ece9ff, var(--eu-teal-soft));
      color: var(--eu-navy-700);
    }
    .ai-tag mat-icon,
    .masking mat-icon {
      font-size: 14px;
      width: 14px;
      height: 14px;
    }
    .masking {
      display: inline-flex;
      align-items: center;
      gap: 3px;
      color: var(--ok);
    }
    .votes {
      display: inline-flex;
      align-items: center;
      gap: 6px;
      margin-left: auto;
      white-space: nowrap;
    }
    .vote {
      display: inline-flex;
      align-items: center;
      gap: 3px;
      border: 1px solid var(--app-line);
      background: var(--app-card);
      border-radius: 999px;
      padding: 2px 8px;
      cursor: pointer;
      color: var(--app-muted);
      font: inherit;
    }
    .vote:hover:not(:disabled) {
      border-color: var(--eu-navy-400);
      color: var(--eu-navy-600);
    }
    .vote.on {
      background: var(--info-soft);
      border-color: var(--info);
      color: var(--info);
    }
    .vote mat-icon {
      font-size: 14px;
      width: 14px;
      height: 14px;
    }
  `,
})
export class AiMeta<T = unknown> {
  readonly result = input.required<StoredInsight<T>>();
  readonly changed = output<StoredInsight<T>>();
  protected readonly busy = signal(false);
  protected readonly label = modelLabel;
  private readonly http = inject(HttpClient);

  protected vote(v: 1 | -1): void {
    const next = this.result().myVote === v ? 0 : v;
    this.busy.set(true);
    this.http
      .post<StoredInsight<T>>(apiUrl(`ai/insights/${this.result().id}/feedback`), { vote: next })
      .subscribe({
        next: (r) => {
          this.busy.set(false);
          this.changed.emit(r);
        },
        error: () => this.busy.set(false),
      });
  }
}
